// ============================================
// i18n Engine
// ============================================

function detectLanguage() {
    // 1. Check URL param (?lang=en)
    const urlParams = new URLSearchParams(window.location.search);
    const urlLang = urlParams.get('lang');
    if (urlLang && translations[urlLang]) return urlLang;

    // 2. Check localStorage
    const savedLang = localStorage.getItem('devotion-lang');
    if (savedLang && translations[savedLang]) return savedLang;

    // 3. Detect browser language
    const browserLang = navigator.language.slice(0, 2).toLowerCase();
    if (translations[browserLang]) return browserLang;

    // 4. Default to English
    return 'en';
}

function applyTranslations(lang) {
    const t = translations[lang];
    if (!t) return;

    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (t[key] !== undefined) {
            el.textContent = t[key];
        }
    });

    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        const key = el.getAttribute('data-i18n-placeholder');
        if (t[key] !== undefined) {
            el.placeholder = t[key];
        }
    });

    // Update HTML lang attribute
    document.documentElement.lang = lang === 'pt' ? 'pt-BR' : lang === 'zh' ? 'zh-CN' : lang;

    // Update active state in switcher
    document.querySelectorAll('.lang-btn').forEach(btn => {
        btn.classList.toggle('active', btn.dataset.lang === lang);
    });

    // Save preference
    localStorage.setItem('devotion-lang', lang);
    window.__currentLang = lang;
}

function initI18n() {
    const lang = detectLanguage();
    applyTranslations(lang);

    // Bind language switcher buttons
    document.querySelectorAll('.lang-btn').forEach(btn => {
        btn.addEventListener('click', () => {
            applyTranslations(btn.dataset.lang);
        });
    });
}

// Export for external use
window.DevotionI18n = { applyTranslations, detectLanguage, translations, initI18n };
